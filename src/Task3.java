import java.util.Scanner; // Scanner нужен, чтобы читать числа с клавиатуры.

/*
 * Практическая работа № 1. Задание 3, вариант 10.
 *
 * Условие: даны три числа. Найти сумму двух наибольших из них.
 * Задание нужно выполнить с использованием условного оператора if.
 *
 * Идея решения:
 * сумма двух наибольших = (сумма всех трёх чисел) - (наименьшее число).
 * Например: 3, 7, 5 -> сумма всех = 15, наименьшее = 3,
 * значит сумма двух наибольших = 15 - 3 = 12 (это 7 + 5).
 */
public class Task3 {

    // Точка входа: с этого метода начинается выполнение программы.
    public static void main(String[] args) {

        // Создаём Scanner для чтения данных с клавиатуры.
        Scanner scanner = new Scanner(System.in);

        // Читаем первое число с помощью вспомогательного метода readDouble.
        System.out.print("Введите первое число: ");
        double a = readDouble(scanner);

        // Читаем второе число.
        System.out.print("Введите второе число: ");
        double b = readDouble(scanner);

        // Читаем третье число.
        System.out.print("Введите третье число: ");
        double c = readDouble(scanner);

        // Пока предполагаем, что наименьшее число — это a.
        double min = a;

        // Если b меньше текущего минимума, запоминаем b как новый минимум.
        // Это и есть условный оператор if.
        if (b < min) {
            min = b;
        }

        // Если c меньше текущего минимума, запоминаем c.
        if (c < min) {
            min = c;
        }

        // Сумма всех чисел минус наименьшее = сумма двух наибольших.
        double sum = a + b + c - min;

        // Выводим ответ.
        System.out.println("Сумма двух наибольших чисел = " + sum);

        // Закрываем Scanner.
        scanner.close();
    }

    // Вспомогательный метод: читает строку и превращает её в число double.
    // Нужен, чтобы дробное число можно было ввести и через запятую, и через точку.
    private static double readDouble(Scanner scanner) {
        // nextLine() читает всю строку, введённую пользователем.
        // trim() убирает пробелы в начале и конце.
        // replace(',', '.') заменяет запятую на точку.
        String text = scanner.nextLine().trim().replace(',', '.');

        // Double.parseDouble переводит текст (например, "2.5") в число 2.5.
        return Double.parseDouble(text);
    }
}
