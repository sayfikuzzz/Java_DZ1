/*
 * Практическая работа № 1. Задание 1, вариант 30.
 *
 * В исходном файле var_30.txt были даны объявления переменных с ошибками.
 * Ниже каждая строка исправлена. В комментарии написано:
 *   - как было в задании;
 *   - что было не так;
 *   - почему сделано именно такое исправление.
 *
 * Главное правило: программа должна компилироваться и запускаться.
 */
public class Task1 {

    // Точка входа в программу: с этого метода Java начинает выполнение.
    public static void main(String[] args) {

        // Было: String words = 6200.954605775894054
        // Ошибки: строку (String) нельзя записать без кавычек,
        // а в конце не хватает точки с запятой.
        // Исправление: взяли число в кавычки и поставили ';'.
        String words = "6200.954605775894054";

        // Было: integer g = "торт"
        // В Java нет типа integer (есть int и Integer).
        // Здесь хранится слово, поэтому нужен тип String и ';'.
        String g = "торт";

        // Было: int q = 'y'
        // В одинарных кавычках записывается один символ (char), а не число.
        // Исправление: тип char и точка с запятой.
        char q = 'y';

        // Было: number k = '7';
        // В Java нет типа number. '7' — это символ, значит нужен char.
        char k = '7';

        // Было: . . . f = 'R'
        // Пропущен тип переменной и точка с запятой.
        // 'R' — один символ, поэтому тип char.
        char f = 'R';

        // Было: boolean value = 'b'
        // boolean хранит только true/false, символ в него положить нельзя.
        // 'b' — символ, поэтому меняем тип на char.
        char value = 'b';

        // Было: boolean m = 'p'
        // Та же ошибка: символ нельзя хранить в boolean. Нужен char.
        char m = 'p';

        // Было: Char value = 'V'
        // 1) Названия типов пишутся с маленькой буквы: char, а не Char.
        // 2) Переменная value уже объявлена выше, повторять имя нельзя.
        // Поэтому назвали её value2 и добавили ';'.
        char value2 = 'V';

        // Было: char case = "снежинка"
        // 1) case — зарезервированное слово Java, его нельзя использовать как имя.
        // 2) "снежинка" — это строка (String), а не один символ (char).
        // Исправление: тип String, безопасное имя caseWord и ';'.
        String caseWord = "снежинка";

        // Было: boolean h = 3948.8198033295279465;
        // boolean не хранит числа. Дробное число — это тип double.
        double h = 3948.8198033295279465;

        // Было: int int = "арбуз";
        // 1) int — ключевое слово, его нельзя использовать как имя переменной.
        // 2) "арбуз" — строка, значит тип String.
        String intName = "арбуз";

        // Было: int c = 3638.9899930539180678
        // Дробное число нельзя без потери дробной части положить в int,
        // поэтому используем double. Также добавлена ';'.
        double c = 3638.9899930539180678;

        // Было: integer b = "торт"
        // integer — не тип Java; "торт" — строка. Нужен String и ';'.
        String b = "торт";

        // Было: float java = 5354.026246480443946257
        // 1) В конце не хватает ';'.
        // 2) Дробное число по умолчанию имеет тип double.
        //    Для float нужен суффикс f, поэтому выбрали double.
        double java = 5354.026246480443946257;

        // Было: byte java = 'e'
        // 1) Имя java уже занято переменной выше — переименовали в javaByte.
        // 2) Символ 'e' имеет код 101 и помещается в byte,
        //    поэтому запись byte javaByte = 'e'; допустима.
        byte javaByte = 'e';

        // Выводим значения, чтобы было видно: программа действительно работает.
        System.out.println("words = " + words);
        System.out.println("g = " + g);
        System.out.println("q = " + q);
        System.out.println("k = " + k);
        System.out.println("f = " + f);
        System.out.println("value = " + value);
        System.out.println("m = " + m);
        System.out.println("value2 = " + value2);
        System.out.println("caseWord = " + caseWord);
        System.out.println("h = " + h);
        System.out.println("intName = " + intName);
        System.out.println("c = " + c);
        System.out.println("b = " + b);
        System.out.println("java = " + java);
        System.out.println("javaByte = " + javaByte);
    }
}
